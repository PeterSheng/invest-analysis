# ---------------- 基础形状函数 ----------------
def gr(w, g, n):
    r = (1 + g) / (1 + w)
    return n / (1 + w) if abs(g - w) < 1e-12 else r * (1 - r ** n) / (1 - r)

def dcf55(f, g1, g2, w, tg):
    """5 年 g1 + 5 年 g2 + TV@10。"""
    f5 = f * (1 + g1) ** 5; f10 = f5 * (1 + g2) ** 5
    return f * gr(w, g1, 5) + f5 * gr(w, g2, 5) / (1 + w) ** 5 + f10 * (1 + tg) / (w - tg) / (1 + w) ** 10

def dcf10(f, g, w, tg):
    """单段 10 年 g + TV@10。"""
    f10 = f * (1 + g) ** 10
    return f * gr(w, g, 10) + f10 * (1 + tg) / (w - tg) / (1 + w) ** 10

def sn2_8(f, g1, g2, w, tg):
    """2 年 g1 + 8 年 g2 + TV@10（实耐宝）。"""
    f2 = f * (1 + g1) ** 2; f10 = f2 * (1 + g2) ** 8
    return f * gr(w, g1, 2) + f2 * gr(w, g2, 8) / (1 + w) ** 2 + f10 * (1 + tg) / (w - tg) / (1 + w) ** 10

def path_dcf(f, path, w, tg):
    """逐年增速 path + TV@len(path)。"""
    c = f; fcfs = []
    for g in path:
        c *= 1 + g; fcfs.append(c)
    ev = sum(x / (1 + w) ** (t + 1) for t, x in enumerate(fcfs))
    return ev + fcfs[-1] * (1 + tg) / (w - tg) / (1 + w) ** len(path)

def fade5(f, g, w, tg):
    """10 年 @g + 5 年线性衰减到 tg + TV@15（万事达）。"""
    fcfs = [f * (1 + g) ** t for t in range(1, 11)]; step = (g - tg) / 5
    for t in range(1, 6):
        fcfs.append(fcfs[-1] * (1 + g - t * step))
    ev = sum(c / (1 + w) ** (t + 1) for t, c in enumerate(fcfs))
    return ev + fcfs[-1] * (1 + tg) / (w - tg) / (1 + w) ** 15

def g10(f, g, w, tg):
    """矩阵用：10 年 @g + TV@10。"""
    fcfs = [f * (1 + g) ** t for t in range(1, 11)]
    ev = sum(c / (1 + w) ** (t + 1) for t, c in enumerate(fcfs))
    return ev + fcfs[-1] * (1 + tg) / (w - tg) / (1 + w) ** 10

def tencent(L, gterm, r, f0=1300.0):
    """腾讯：4 年过渡到终态净利 L + 6 年持有 L + TV@gterm。"""
    g = (L / f0) ** 0.25 - 1
    fcfs = [f0 * (1 + g) ** t for t in range(1, 5)]
    ev = sum(c / (1 + r) ** (t + 1) for t, c in enumerate(fcfs))
    ev += L * sum(1 / (1 + r) ** t for t in range(5, 11))
    return ev + L * (1 + gterm) / (r - gterm) / (1 + r) ** 10

def meidi(f, g1, w, tg):
    """5 年 g1 + TV@5（美的/福耀乐观）。"""
    f5 = f * (1 + g1) ** 5
    return f * gr(w, g1, 5) + f5 * (1 + tg) / (w - tg) / (1 + w) ** 5

def google(f, g, w, tg):
    """线性 fade 到 tg 的 10 年 + TV@10（谷歌）。"""
    c = f; ev = 0
    for t in range(1, 11):
        gt = g - (g - tg) * (t - 1) / 9
        c *= 1 + gt; ev += c / (1 + w) ** t
    return ev + c * (1 + tg) / (w - tg) / (1 + w) ** 10

def eqix(f, g1, g2, w, mult):
    """EQIX：10 年 DCF + 终值用 EV/EBITDA 倍数（ratio 法专用）。"""
    f5 = f * (1 + g1) ** 5; f10 = f5 * (1 + g2) ** 5
    return f * gr(w, g1, 5) + f5 * gr(w, g2, 5) / (1 + w) ** 5 + mult * f10 / (1 + w) ** 10

def fit(pts):
    n = len(pts); sx = sum(p[0] for p in pts); sy = sum(p[1] for p in pts)
    sxx = sum(p[0] ** 2 for p in pts); sxy = sum(p[0] * p[1] for p in pts)
    a = (n * sxy - sx * sy) / (n * sxx - sx * sx); b = (sy - a * sx) / n
    return a, b

def bisect(fn, lo, hi):
    flo = fn(lo)
    for _ in range(80):
        mid = (lo + hi) / 2; fm = fn(mid)
        if abs(fm) < 1e-7:
            return mid
        if (flo < 0) != (fm < 0):
            hi = mid
        else:
            lo = mid; flo = fm
    return (lo + hi) / 2

