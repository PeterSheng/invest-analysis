def eval_scen(spec, w, tg):
    """spec=[模型名,参数...]；w/tg 注入到参数中（tencent 的 gterm 亦注入统一 tg）。"""
    name, args = spec[0], list(spec[1:])
    if name == "tencent":
        return tencent(args[0], tg, w)   # 统一参数轮：gterm 注入统一 tg（spec 第3参为旧口径占位）
    if name == "google":
        return google(args[0], args[1], w, tg)
    if name in ("dcf55", "sn2_8"):
        return MODELS[name](args[0], args[1], args[2], w, tg)
    if name == "dcf10":
        return dcf10(args[0], args[1], w, tg)
    if name == "path_dcf":
        return path_dcf(args[0], args[1], w, tg)
    if name == "fade5":
        return fade5(args[0], args[1], w, tg)
    if name == "meidi":
        return meidi(args[0], args[1], w, tg)
    if name == "eqix":
        return eqix(args[0], args[1], args[2], w, args[3])
    raise ValueError(name)

